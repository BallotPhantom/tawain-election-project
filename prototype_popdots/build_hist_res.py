#!/usr/bin/env python3
"""Leader + margin per population-light unit (village / township pool from build_hist_lights.py) for the history page's
人口光點 toggle (user 2026-11-08: single-winner races only, 「先以2024,2022的嘗試就好」).

    python3 prototype_popdots/build_hist_res.py   → prototype_popdots/data_hist_res.js (history-page toggle removed 2026-11-08)

HL_RES = {race: [[party, margin %] | null, ...]}   index = HL_UNITS index; margin = (1st − 2nd) / the candidates' votes
  mayor2022  縣市長 2022 — mayor_2022_tc_data.js MAYOR_2022_VILL (CEC village results)
  pres2024   總統 2024   — v2/data_pres.js PRES_HIST['2024'] (CEC files; vc: [elig, cast, valid, v0, v1, v2]; a village
                           voting at a joint station (jv → jr) takes that station's result)
  leg2024    區域立委 2024 — data_vc_ed_legis.js VC_ED (village × the district's candidates)
A unit whose village code isn't in a race's results (codes changed since, or a township pool) takes its township's
result, summed from that township's villages.
"""
import collections, json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
from poll_live2026 import load_js  # noqa: E402


def const_json(path, var):
    s = open(os.path.join(ROOT, path), encoding='utf-8').read()
    m = re.search(r'const %s\s*=\s*' % var, s); i = m.end()
    return json.JSONDecoder().raw_decode(s[i:])[0]


def lead(votes):   # {party-or-candidate key: (party, votes)} → [party, margin]
    vs = sorted(votes, key=lambda x: -x[1]); tot = sum(v for _, v in vs)
    if not tot: return None
    return [vs[0][0], round((vs[0][1] - (vs[1][1] if len(vs) > 1 else 0)) / tot * 100, 1)]


def race_res(units, by_vc):
    """by_vc: {vc11: [(party, votes), ...]} → per unit [party, margin]; township fallback = the township's villages summed
    per candidate position (the same candidates throughout a township for these races)."""
    by_tc = collections.defaultdict(dict)
    for vc, vs in by_vc.items():
        acc = by_tc[vc[:8]]
        for i, (p, v) in enumerate(vs): acc[i] = (p, acc.get(i, (p, 0))[1] + v)
    out, nv, nt, nn = [], 0, 0, 0
    for u in units:
        code = u[5:] if u.startswith('pool:') else u
        r = None
        if not u.startswith('pool:') and code in by_vc: r = lead(by_vc[code]); nv += 1
        elif code[:8] in by_tc: r = lead(list(by_tc[code[:8]].values())); nt += 1
        if r is None: nn += 1
        out.append(r)
    return out, (nv, nt, nn)


def main():
    units = const_json('prototype_popdots/data_hist_lights.js', 'HL_UNITS')
    res, stats = {}, {}

    V = load_js(os.path.join(ROOT, 'mayor_2022_tc_data.js'), 'MAYOR_2022_VILL')
    res['mayor2022'], stats['mayor2022'] = race_res(units, {vc: [(c['p'], c['v']) for c in e['cands']] for vc, e in V.items()})

    P = const_json('v2/data_pres.js', 'PRES_HIST')['2024']
    parties = [c[1] for c in P['cands']]
    pv = {vc: [(parties[i], v) for i, v in enumerate(row[3:])] for vc, row in P['vc'].items()}
    for vc, jid in P['jv'].items():
        if vc not in pv: pv[vc] = [(parties[i], v) for i, v in enumerate(P['jr'][jid][4:])]
    res['pres2024'], stats['pres2024'] = race_res(units, pv)

    E = const_json('data_vc_ed_legis.js', 'VC_ED')
    lv = {vc: [(c['p'], c['n']) for c in sorted(e['votes'].values(), key=lambda c: -c['n'])] for vc, e in E.items()}
    # township fallback must not mix districts: a township split between districts sums each candidate under its own
    # position, so for 立委 sum by candidate name instead
    by_tc = collections.defaultdict(lambda: collections.defaultdict(lambda: ['', 0]))
    for vc, e in E.items():
        for n, c in e['votes'].items(): r = by_tc[vc[:8]][n]; r[0] = c['p']; r[1] += c['n']
    out, nv, nt, nn = [], 0, 0, 0
    for u in units:
        code = u[5:] if u.startswith('pool:') else u
        r = None
        if not u.startswith('pool:') and code in lv: r = lead(lv[code]); nv += 1
        elif code[:8] in by_tc: r = lead([tuple(x) for x in by_tc[code[:8]].values()]); nt += 1
        if r is None: nn += 1
        out.append(r)
    res['leg2024'], stats['leg2024'] = out, (nv, nt, nn)

    for k, (nv, nt, nn) in stats.items():
        print(k, 'village result', nv, 'township fallback', nt, 'none', nn)
    with open(os.path.join(HERE, 'data_hist_res.js'), 'w', encoding='utf-8') as f:
        f.write('// leader per population-light unit — generated by prototype_popdots/build_hist_res.py; do not hand-edit.\n')
        f.write('const HL_RES = %s;\n' % json.dumps(res, ensure_ascii=False, separators=(',', ':')))
    print('wrote prototype_popdots/data_hist_res.js', os.path.getsize(os.path.join(HERE, 'data_hist_res.js')) // 1024, 'KB')


if __name__ == '__main__':
    main()
